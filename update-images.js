#!/usr/bin/env node
/* =====================================================================
   update-images.js  —  run after adding / renaming photos in /images

     node update-images.js                 check against the live Google Sheet (link in config.js)
     node update-images.js --csv file.csv  check against a local CSV instead
     node update-images.js --no-check      just rebuild the file list

   1. Rebuilds images/manifest.json  (read by the LIVE site every few minutes)
      and images/manifest.js         (bundled fallback / local file:// use)
   2. Cross-checks the sheet's [image] column with the folder and tells you:
        • file names in the sheet that don't exist in /images
        • photos in /images that no row uses (and no entry-number match)
        • oversized files (> 2 MB) that will load slowly
   Needs Node 18+. No packages to install.
   ===================================================================== */
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, 'images');
const IMG = /\.(jpe?g|png|webp|gif|avif)$/i;

const files = fs.readdirSync(dir).filter(f => IMG.test(f) && !f.startsWith('.'))
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
fs.writeFileSync(path.join(dir, 'manifest.json'), JSON.stringify(files, null, 2) + '\n');
fs.writeFileSync(path.join(dir, 'manifest.js'),
  '// Auto-generated by update-images.js — lists the files in /images.\nwindow.THIRD_SPACES_IMAGES = ' + JSON.stringify(files, null, 2) + ';\n');
console.log(`✔ manifest updated: ${files.length} images`);

const big = files.filter(f => fs.statSync(path.join(dir, f)).size > 2 * 1024 * 1024);
if (big.length) console.log(`⚠ over 2 MB (resize to ~1400px): ${big.join(', ')}`);
if (process.argv.includes('--no-check')) process.exit(0);

function parseCSV(text) {
  const rows = []; let row = [], cell = '', q = false; text = text.replace(/^\uFEFF/, '');
  for (let i = 0; i < text.length; i++) {
    const c = text[i], n = text[i + 1];
    if (c === '"' && q && n === '"') { cell += '"'; i++; }
    else if (c === '"') q = !q;
    else if (c === ',' && !q) { row.push(cell); cell = ''; }
    else if ((c === '\n' || c === '\r') && !q) { if (c === '\r' && n === '\n') i++; row.push(cell); if (row.some(v => v.trim())) rows.push(row); row = []; cell = ''; }
    else cell += c;
  }
  if (cell || row.length) { row.push(cell); if (row.some(v => v.trim())) rows.push(row); }
  const head = rows.shift().map(h => h.trim().toLowerCase());
  return rows.map(r => Object.fromEntries(head.map((h, i) => [h, (r[i] || '').trim()])));
}

(async () => {
  let text;
  const ci = process.argv.indexOf('--csv');
  try {
    if (ci > -1) text = fs.readFileSync(process.argv[ci + 1], 'utf8');
    else {
      const cfg = fs.readFileSync(path.join(__dirname, 'config.js'), 'utf8');
      const url = (cfg.match(/THIRD_SPACES_CSV_URL\s*=\s*"([^"]+)"/) || [])[1];
      if (!url) throw new Error('no THIRD_SPACES_CSV_URL in config.js');
      text = await (await fetch(url)).text();
    }
  } catch (e) { console.log('(skipped sheet check: ' + e.message + ')'); return; }

  const rows = parseCSV(text), lower = new Map(files.map(f => [f.toLowerCase(), f])), stems = new Map(files.map(f => [f.replace(/\.[^.]+$/, '').toLowerCase(), f]));
  const used = new Set(); let missing = 0;
  for (const r of rows) {
    const name = r['place / name'] || r['name'] || r['place'], id = parseInt(r['#'] || r['id'], 10);
    const cell = r['[image]'] || r['image'] || r['images'] || '';
    const toks = cell.split(/[|;\n]+|,(?=\s*\S+\.(?:jpe?g|png|webp|gif|avif)\b)/i).map(s => s.trim()).filter(Boolean);
    for (const t of toks) {
      if (/^https?:|^data:/i.test(t)) continue;
      const base = t.replace(/^\.?\/*(images\/)?/i, '');
      const hit = lower.get(base.toLowerCase()) || stems.get(base.replace(/\.[^.]+$/, '').toLowerCase());
      if (hit) used.add(hit); else { missing++; console.log(`✖ "${name}" (#${id}): "${t}" is not in /images`); }
    }
    if (!toks.length && id) files.filter(f => new RegExp('^0*' + id + '(?![0-9])').test(f)).forEach(f => used.add(f));
  }
  files.filter(f => !used.has(f)).forEach(f => console.log(`• not used by any row yet: ${f}`));
  console.log(missing ? `\n${missing} file name(s) in the sheet still need a matching photo.` : '\n✔ every file name in the sheet has a photo.');
})();
