#!/usr/bin/env node
/* =====================================================================
   geocode.js  —  finds latitude / longitude for every place so the map view can pin it

     node geocode.js                  read the live Google Sheet (link in config.js)
     node geocode.js --csv file.csv   read a local CSV instead
     node geocode.js --redo           look everything up again (default: only new places)
     node geocode.js --dry            just list who would be looked up (no internet needed)
     node geocode.js --email you@example.com   identify yourself to the services (polite; optional)

   Writes coords.js next to index.html. Upload it with the rest of the site.
   Places whose sheet row already has "lat" and "lng" columns are skipped.
   Looks addresses up with the US Census Bureau's free geocoder first (no key, no rate-limit trouble for
   US street addresses), then falls back to OpenStreetMap's Nominatim for any it can't match.
   Needs Node 18+. No packages to install.
   ===================================================================== */
const fs = require('fs'), path = require('path');
const OUT = path.join(__dirname, 'coords.js');
const arg = f => process.argv.includes(f);

function parseCSV(text) {
  const rows = []; let row = [], cell = '', q = false; text = text.replace(/^\uFEFF/, '');
  for (let i = 0; i < text.length; i++) {
    const c = text[i], n = text[i + 1];
    if (c === '"' && q && n === '"') { cell += '"'; i++; }
    else if (c === '"') q = !q;
    else if (c === ',' && !q) { row.push(cell); cell = ''; }
    else if ((c === '\n' || c === '\r') && !q) { if (c === '\r' && n === '\n') i++; row.push(cell); if (row.some(v => v.trim())) rows.push(row); row = []; cell = ''; }
    else cell += c;
  }
  if (cell || row.length) { row.push(cell); if (row.some(v => v.trim())) rows.push(row); }
  const head = rows.shift().map(h => h.trim().toLowerCase());
  return rows.map(r => Object.fromEntries(head.map((h, i) => [h, (r[i] || '').trim()])));
}

// must match keyOf() in map.js
const keyOf = (name, address) => `${name}|${address}`.toLowerCase().normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9|]+/g, ' ').trim();
const sleep = ms => new Promise(r => setTimeout(r, ms));

function readExisting() {
  try {
    const t = fs.readFileSync(OUT, 'utf8');
    return JSON.parse(t.slice(t.indexOf('{'), t.lastIndexOf('}') + 1));
  } catch (e) { return {}; }
}
function save(coords) {
  const keys = Object.keys(coords).sort();
  const body = keys.map(k => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(coords[k])).join(',\n');
  fs.writeFileSync(OUT,
    '// Auto-generated by geocode.js — latitude / longitude for each place, used by the map view.\n' +
    '// Run `node geocode.js` after adding places to fill this in.\n' +
    'window.THIRD_SPACES_COORDS = {\n' + body + '\n};\n');
}

const ei = process.argv.indexOf('--email');
const UA = 'third-space-index-geocoder (student project' + (ei > -1 ? '; contact: ' + process.argv[ei + 1] : '') + ')';

/* 1. US Census Bureau — street addresses only, so shop / suite words are trimmed first */
async function census(address) {
  const clean = address.replace(/[,\s]+(?:store|suite|ste|unit|apt|floor|fl|rm|room)\.?\s*[\w-]+/ig, '').replace(/\s+#\s*\w+/g, '');
  const url = 'https://geocoding.geo.census.gov/geocoder/locations/onelineaddress?benchmark=Public_AR_Current&format=json&address=' + encodeURIComponent(clean);
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error('Census HTTP ' + res.status);
  const m = (((await res.json()).result || {}).addressMatches || [])[0];
  return m && m.coordinates ? [+(+m.coordinates.y).toFixed(6), +(+m.coordinates.x).toFixed(6)] : null;
}

/* 2. OpenStreetMap Nominatim — fallback. If it says slow down once, it is skipped for the rest of this run. */
let osmBlocked = false;
async function osm(q) {
  if (osmBlocked) return null;
  const url = 'https://nominatim.openstreetmap.org/search?format=jsonv2&limit=1&countrycodes=us&q=' + encodeURIComponent(q);
  const res = await fetch(url, { headers: { 'User-Agent': UA, 'Accept': 'application/json' } });
  if (res.status === 429 || res.status === 403 || res.status === 503) { osmBlocked = true; console.log(`  (OpenStreetMap says slow down — HTTP ${res.status}; skipping it for this run)`); return null; }
  if (!res.ok) throw new Error('OpenStreetMap HTTP ' + res.status);
  const hit = (await res.json())[0];
  await sleep(1500);
  return hit ? [+(+hit.lat).toFixed(6), +(+hit.lon).toFixed(6)] : null;
}

async function lookup(p) {
  let c = null, err = '';
  try { c = await census(p.address); } catch (e) { err = e.message; }
  await sleep(250);
  if (!c) { try { c = await osm(p.address) || await osm(p.name + ', ' + p.address); } catch (e) { err = e.message; } }
  return { c, err };
}

(async () => {
  let text;
  const ci = process.argv.indexOf('--csv');
  if (ci > -1) text = fs.readFileSync(process.argv[ci + 1], 'utf8');
  else {
    const cfg = fs.readFileSync(path.join(__dirname, 'config.js'), 'utf8');
    const url = (cfg.match(/THIRD_SPACES_CSV_URL\s*=\s*"([^"]+)"/) || [])[1];
    if (!url) { console.log('No THIRD_SPACES_CSV_URL in config.js — use --csv third-space-index.csv'); process.exit(1); }
    text = await (await fetch(url)).text();
  }

  const coords = arg('--redo') ? {} : readExisting();
  const todo = [];
  for (const r of parseCSV(text)) {
    const name = r['place / name'] || r['name'] || r['place'] || '', address = r['address'] || '';
    if (!name) continue;
    if (r['lat'] && r['lng']) continue;                       // the sheet already has coordinates
    if (!address) { console.log(`• "${name}" has no address — skipped`); continue; }
    if (!coords[keyOf(name, address)]) todo.push({ name, address });
  }
  console.log(todo.length ? `${todo.length} place(s) to look up.` : '✔ every place already has coordinates.');
  if (arg('--dry')) { todo.forEach(p => console.log('  ' + p.name + ' — ' + p.address)); return; }

  let ok = 0; const bad = [];
  process.on('SIGINT', () => { save(coords); console.log('\nStopped — progress saved to coords.js. Run again to continue.'); process.exit(0); });
  for (const [i, p] of todo.entries()) {
    const { c, err } = await lookup(p);
    if (c) { coords[keyOf(p.name, p.address)] = c; ok++; save(coords); console.log(`✔ ${i + 1}/${todo.length}  ${p.name}  ${c.join(', ')}`); }
    else { bad.push(p); console.log(`✖ ${i + 1}/${todo.length}  ${p.name} — ${err || 'address not found'}`); }
  }
  save(coords);
  console.log(`\nWrote ${Object.keys(coords).length} place(s) to coords.js.`);
  if (bad.length) console.log(`Could not find ${bad.length}:\n` + bad.map(p => `  ${p.name} — ${p.address}`).join('\n') +
    '\nFix the address in the sheet, or add "lat" and "lng" columns for those rows.');
})();
